import { dateKey } from './localtime.js';

const CHROME_LINES = [
  /^shared conversation$/i,
  /^this shared conversation is generated by ai/i,
  /^该分享由\s*ai\s*生成/i,
  /^本对话由\s*ai\s*生成/i,
  /^continue with deepseek$/i,
  /^继续与\s*deepseek\s*对话$/i,
  /^copy$/i,
  /^download$/i,
  /^复制$/i,
  /^下载$/i,
];

const USER_MARK = /^\s*(?:\*\*)?\s*[\[【]?\s*(用户|提问者|我|user|human|you)\s*(?:\s+(?:said|says|说))?\s*[\]】]?\s*(?:\*\*)?\s*[:：]\s*(.*)$/i;
const AI_MARK = /^\s*(?:\*\*)?\s*[\[【]?\s*(deepseek|assistant|ai|助手|模型|回答)\s*(?:\s+(?:said|says|说))?\s*[\]】]?\s*(?:\*\*)?\s*[:：]\s*(.*)$/i;
const THINK_MARK = /^\s*(?:thought for\s+[\d.]+\s*(?:seconds?|secs?|s)|已?思考[（(]?用时\s*[\d.]+\s*秒[)）]?|思考了\s*[\d.]+\s*秒|深度思考)\s*$/i;

function isChrome(line) {
  const t = line.trim();
  if (!t) return false;
  return CHROME_LINES.some((re) => re.test(t));
}

function trimChrome(lines) {
  let start = 0;
  let end = lines.length;
  while (start < end && (!lines[start].trim() || isChrome(lines[start]))) start += 1;
  while (end > start && (!lines[end - 1].trim() || isChrome(lines[end - 1]))) end -= 1;
  return lines.slice(start, end);
}

function pushMessage(list, role, text) {
  const content = text.replace(/\n{3,}/g, '\n\n').trim();
  if (!content) return;
  list.push({
    role,
    ts: null,
    parts: [{ type: role === 'user' ? 'request' : 'response', label: role === 'user' ? '提问' : '回答', content }],
  });
}

/**
 * 「粘贴全文」兜底解析。
 * 支持的写法（任一）：
 *   1. 角色标记行：用户：/ DeepSeek： / Assistant: / 【用户】
 *   2. DeepSeek 网页复制出来的原文里带「Thought for N seconds」，按它切分问答
 *   3. 都没有 → 整段作为一条未标注角色的内容，仍然生成文档
 */
export function parsePastedText(rawText, options = {}) {
  const timeZone = options.timeZone;
  const warnings = [];
  const text = String(rawText || '').replace(/\r\n?/g, '\n');
  if (!text.trim()) {
    const err = new Error('粘贴内容为空');
    err.code = 'EMPTY_INPUT';
    throw err;
  }

  const lines = trimChrome(text.split('\n'));

  const userHits = [];
  const aiHits = [];
  lines.forEach((line, i) => {
    if (USER_MARK.test(line)) userHits.push(i);
    if (AI_MARK.test(line)) aiHits.push(i);
  });
  const markerCount = userHits.length + aiHits.length;

  const messages = [];

  if (markerCount >= 2) {
    let role = null;
    let buffer = [];
    const flush = () => {
      if (role) pushMessage(messages, role, buffer.join('\n'));
      buffer = [];
    };
    for (const line of lines) {
      const u = line.match(USER_MARK);
      const a = u ? null : line.match(AI_MARK);
      if (u) {
        flush();
        role = 'user';
        if (u[2]) buffer.push(u[2]);
        continue;
      }
      if (a) {
        flush();
        role = 'assistant';
        if (a[2]) buffer.push(a[2]);
        continue;
      }
      if (role) buffer.push(line);
    }
    flush();
    warnings.push('按角色标记（用户 / DeepSeek）切分了消息。');
  } else {
    const thinkHits = lines.map((l, i) => (THINK_MARK.test(l) ? i : -1)).filter((i) => i >= 0);
    if (thinkHits.length > 0) {
      let cursor = 0;
      for (const hit of thinkHits) {
        const before = lines.slice(cursor, hit).join('\n');
        pushMessage(messages, 'user', before);
        const next = thinkHits.find((h) => h > hit) ?? lines.length;
        const body = lines.slice(hit, next).join('\n');
        pushMessage(messages, 'assistant', body);
        cursor = next;
      }
      pushMessage(messages, 'user', lines.slice(cursor).join('\n'));
      warnings.push('未发现角色标记，按「Thought for N seconds」等思考提示切分了问答；思考过程保留在正文里。');
    } else {
      pushMessage(messages, 'unknown', lines.join('\n'));
      warnings.push(
        '没有识别出角色标记，已把整段内容作为一条记录。若想区分「用户 / DeepSeek」，可在每段前加一行「用户：」或「DeepSeek：」再转换。',
      );
    }
  }

  if (messages.length === 0) {
    const err = new Error('没有从粘贴内容里解析出任何正文');
    err.code = 'EMPTY_INPUT';
    throw err;
  }

  // 没有逐条时间，统一挂到用户指定（或当天）的日期
  const baseDate = options.date && /^\d{4}-\d{2}-\d{2}$/.test(options.date)
    ? options.date
    : dateKey(Date.now(), timeZone);

  const title =
    String(options.title || '').trim() ||
    messages.find((m) => m.role !== 'assistant')?.parts[0]?.content.split('\n')[0].slice(0, 28) ||
    '粘贴的 DeepSeek 对话';

  warnings.push('粘贴模式没有逐条时间戳，全部按你指定的日期归档，时间粒度只到日。');

  const lower = text.toLowerCase();
  const pasteSource = /deepseek/.test(lower) ? 'DeepSeek' : '粘贴内容';

  return {
    title,
    titleSource: options.title ? 'user' : 'derived',
    platform: 'paste',
    sourceLabel: `粘贴全文（${pasteSource}）`,
    modelLabel: '',
    shareId: null,
    sourceUrl: null,
    fetchedAt: Date.now(),
    timeZone,
    timeSource: 'day',
    fallbackDate: baseDate,
    timeNote: `来源未提供逐条时间，本文档按 ${baseDate} 归档，时间粒度只到日。`,
    messages: messages.map((m, i) => ({ ...m, index: i + 1 })),
    warnings,
  };
}
